  static String _stem(String word) {
    final w = _synonyms[word] ?? word;
    if (w.length <= 4) return w;
    final cut = w.length - 2;
    return w.substring(0, cut < 4 ? 4 : cut);
  }

  static List<FoodItem> search(String rawQuery) {
    final query = rawQuery.toLowerCase().replaceAll('ё', 'е').trim();
    if (query.isEmpty) return const [];

    final words = query
        .split(RegExp(r'[\s,.\-()"/]+'))
        .where((w) => w.length >= 2)
        .toList();
    if (words.isEmpty) return const [];

    final allStems = words.map(_stem).toList();
    final coreStems = words
        .where((w) => !_modifiers.contains(w))
        .map(_stem)
        .toList();

    final exactMatches = <({FoodItem item, int score})>[];
    final partialMatches = <({FoodItem item, int score})>[];

    for (final entry in _entries) {
      final hay = '${entry.name} ${entry.keywords}'
          .toLowerCase()
          .replaceAll('ё', 'е');
      final nameLower = entry.name.toLowerCase().replaceAll('ё', 'е');

      final matchedAll = allStems.every((s) => hay.contains(s));
      if (matchedAll) {
        int score = 1500;
        if (nameLower == query) {
          score += 1000;
        } else if (nameLower.startsWith(allStems.first)) {
          score += 400;
        }
        score -= entry.name.length * 2;
        exactMatches.add((item: entry.toFoodItem(), score: score));
      } else if (coreStems.isNotEmpty &&
          coreStems.every((s) => hay.contains(s))) {
        int score = 700 - entry.name.length * 2;
        partialMatches.add((item: entry.toFoodItem(), score: score));
      }
    }

    final chosen = exactMatches.isNotEmpty ? exactMatches : partialMatches;
    chosen.sort((a, b) => b.score.compareTo(a.score));

    return chosen.map((e) => e.item).toList();
  }
