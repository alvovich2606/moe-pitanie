  final String name;
  final double calories;
  final double protein;
  final double fat;
  final double carbs;
  final String keywords;

  const _CatalogEntry(
    this.name,
    this.calories,
    this.protein,
    this.fat,
    this.carbs, [
    this.keywords = '',
  ]);

