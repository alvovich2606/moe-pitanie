    return FoodItem(
      name: name,
      brand: 'Справочник КБЖУ',
      caloriesPer100g: calories,
      proteinPer100g: protein,
      fatPer100g: fat,
      carbsPer100g: carbs,
      isCustom: false,
    );
  }
}

